def character_block(text: str) -> str:
    """Как ассистент говорит — единственное место, где это сказано.

    Раньше манера была правилом в коде, а характер спорил с ней поверх, и модели
    приходилось объяснять, кто главнее. Спорить не с чем: манера ровно одна, просто
    у неё есть значение по умолчанию (`instructions.DEFAULT_CHARACTER`) — то самое
    «тепло и спокойно», с которым панель жила всегда. Написал человек своё — оно и
    стоит на этом месте; ничего не написал — стоит умолчание.

    Что характер не трогает, перечислено в `TONE` и туда же вынесено намеренно:
    ассистент, из-за нрава начавший выдумывать калории или ставить диагнозы, — это
    уже не характер, а другой ассистент.
    """
    if not text:
        return ""
    return f"""\
Как ты говоришь:
«{text}»

Так — в каждой реплике, а не в первой: сбиться на нейтральный тон через пару фраз
значит не сыграть характер вовсе. Это про манеру. Что ты знаешь, какие называешь
цифры и о чём молчишь, характер не меняет.
"""


def rules_block(rules: Sequence[Tuple[int, str]]) -> str:
    """Правила — то, о чём человек договорился с ассистентом однажды.

    Промпт здесь и правда пишет модель: каждая строка сюда попала потому, что
    человек сказал её словами, а ассистент сохранил её инструментом. Поэтому
    блок стоит рядом с характером — обе вещи про то, каким ассистента захотели
    видеть, — и выше `TONE`: то, что не отменяется ничем, читается последним.

    Номер у строки не украшение: им человек ссылается на правило, когда просит
    его снять («забудь про доску самочувствия») или поправить.
    """
    if not rules:
        return ""
    lines = "\n".join(f"- #{number} {text}" for number, text in rules)
    return f"""\
О чём вы с этим человеком договорились — он сказал это однажды, и оно действует всегда:
{lines}

Выполняй, не дожидаясь напоминания и не пересказывая правило вслух: человек его
уже знает, он его и придумал. Правило говорит, что делать; характер — как об этом
говорить; спорить им не о чем. Снять правило может только человек — drop_rule по
его номеру, и только если он об этом попросил.
"""


def memos_block(memos: Sequence[Tuple[str, str]]) -> str:
    """Памятки по областям — то, что человек просил учитывать.

    Это его слова о себе, а не задание пересказать их вслух: человек, написавший
    «нет желчного», ждёт, что ассистент это учтёт, а не что каждый ответ про еду
    будет начинаться с напоминания о его болячках.
    """
    if not memos:
        return ""
    lines = "\n".join(f"- {title}: {text}" for title, text in memos)
    return f"""\
Что этот человек просил учитывать — его собственные слова:
{lines}

Держи это в уме, когда отвечаешь и когда выбираешь инструмент. Вслух не пересказывай
и не напоминай человеку о том, что он сам про себя написал. Это не предписания врача,
а его пожелания: сомневаешься — предложи, а не запрещай.
"""


#: Как называется режим инструмента в разговоре. Слова человеческие: строка
#: уезжает в промпт и оттуда, случается, в ответ человеку.
MODE_WORDS = {
    "auto": "делаешь сам",
    "ask": "спрашиваешь разрешения",
    "off": "не пользуешься вовсе",
}


def autonomy_block(level: int, own: bool, exceptions: Sequence[Tuple[str, str, str]]) -> str:
    """Насколько ассистент самостоятелен — и чей это выбор.

    Чей — не украшение. Общую самостоятельность задал администратор на весь дом,
    и человек, который её не выбирал, о ней может не знать; свою он выставил сам,
    словами или на экране. Ассистенту это нужно, чтобы объяснить человеку, почему
    он переспрашивает, и чтобы не менять вслепую то, что уже стоит (ADR-0012).
    """
    named = AUTONOMY_LEVELS.get(level or 0, "Спрашивает про важное")
    whose = ("это он выбрал себе сам"
             if own else "это общая настройка дома — своей он не задавал")
    block = f"Насколько ты самостоятелен: «{named}» ({whose}).\n"
    if exceptions:
        lines = "\n".join(f"- {title} ({name}): {MODE_WORDS.get(mode, mode)}"
                          for title, name, mode in exceptions)
        block += f"Отдельно про инструменты он попросил вот что:\n{lines}\n"
    block += (
        "Это можно менять его словами: про один инструмент — set_tool_mode, про всё "
        "сразу — set_autonomy. Своё решение он ставит поверх общего; выключенное "
        "администратором на весь дом так не включается.\n"
    )
    return block


def summaries_block(items: Sequence[str]) -> str:
    """Краткие итоги прошлых разговоров — память за пределами окна истории.

    Окно истории — 16 сообщений, и всё старше просто исчезает из виду модели.
    Итоги пишет разбор «Подхода» (по одному предложению на кусок разговора);
    здесь едут последние два-три — не пересказ, а нить: о чём вы вообще
    разговариваете с этим человеком.
    """
    if not items:
        return ""
    lines = "\n".join(f"- {text}" for text in items)
    return f"""\
О чём вы говорили раньше (краткие итоги прошлых разговоров):
{lines}

Опирайся на это молча, как на общую нить разговора. Пересказывать человеку его
же разговоры и цитировать эти строки не надо.
"""


def daypart(hour: int) -> str:
    """Слово о времени суток — факт контекста, не манера (ADR-0006)."""
    if 5 <= hour < 12:
        return "утро"
    if 12 <= hour < 17:
        return "день"
    if 17 <= hour < 23:
        return "вечер"
    return "ночь"


def system_prompt(user: User, modules: List[str], now: datetime = None,
                  character: str = "", memos: Sequence[Tuple[str, str]] = (),
                  autonomy: int = 1, rules: Sequence[Tuple[int, str]] = (),
                  own_autonomy: bool = False,
                  tool_exceptions: Sequence[Tuple[str, str, str]] = ()) -> str:
    now = now or local_now()
    who = f"{user.display_name}"
    if user.relation:
        who += f" ({user.relation})"

    modules_line = ", ".join(modules) if modules else "нет подключённых модулей"

    # Сначала кто ты и как говоришь, потом о чём договорились, и только потом
    # чего всё это не отменяет: манера и уговоры — часть представления, а не
    # поправка к запретам. Порядок здесь смысловой, а не оформительский —
    # правило «считай точно» не должно читаться позже, чем «оценки называй
    # оценками». Памятки — после правил работы, ближе к фактам: это уже не «как
    # говорить», а «что учитывать».
    blocks = [
        "\n".join(part for part in (WHO, character_block(character)) if part),
        rules_block(rules),
        TONE,
        TOOLS_RULES,
        RULES_ROUTING,
        # Правила про еду — только тем, у кого включено питание: незачем занимать
        # контекст того, кто модулем не пользуется. Памятки — тем же правилом:
        # что попало в `memos`, решает вызывающий, а он спрашивает по модулям.
        MEAL_RULES if "nutrition" in modules else "",
        # Про интернет — только тем, у кого модуль «Интернет» включён и поиск
        # настроен: modules собирается из доступных инструментов, так что
        # неработающий search_web сюда не приведёт.
        WEB_RULES if "web" in modules else "",
        memos_block(memos),
        (
            # Время суток — одной строкой-ориентиром: здороваться по нему и
            # держать его в уме, а не пересказывать. Как именно звучит «доброе
            # утро», решает характер, не эта строка.
            f"Сейчас: {now:%d.%m.%Y %H:%M}, {daypart(now.hour)}. Учитывай время "
            f"суток сам: приветствие и уместность предложений зависят от него.\n"
            f"Ты разговариваешь с: {who}. Семья: «{user.family.name if user.family else 'Семья'}».\n"
            f"Включённые модули этого человека: {modules_line}.\n"
            + autonomy_block(autonomy, own_autonomy, tool_exceptions)
        ),
    ]
    return "\n".join(block for block in blocks if block)


