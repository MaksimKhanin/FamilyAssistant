def character_block(text: str) -> str:
    """Как ассистент говорит — единственное место, где это сказано.

    Раньше манера была правилом в коде, а характер спорил с ней поверх, и модели
    приходилось объяснять, кто главнее. Спорить не с чем: манера ровно одна, просто
    у неё есть значение по умолчанию (`instructions.DEFAULT_CHARACTER`) — то самое
    «тепло и спокойно», с которым панель жила всегда. Написал человек своё — оно и
    стоит на этом месте; ничего не написал — стоит умолчание.

    Что характер не трогает, перечислено в `TONE` и туда же вынесено намеренно:
    ассистент, из-за нрава начавший выдумывать калории или ставить диагнозы, — это
    уже не характер, а другой ассистент.
    """
    if not text:
        return ""
    return f"""\
Как ты говоришь:
«{text}»

Так — в каждой реплике, а не в первой: сбиться на нейтральный тон через пару фраз
значит не сыграть характер вовсе. Это про манеру. Что ты знаешь, какие называешь
цифры и о чём молчишь, характер не меняет.
"""


def memos_block(memos: Sequence[Tuple[str, str]]) -> str:
    """Памятки по областям — то, что человек просил учитывать.

    Это его слова о себе, а не задание пересказать их вслух: человек, написавший
    «нет желчного», ждёт, что ассистент это учтёт, а не что каждый ответ про еду
    будет начинаться с напоминания о его болячках.
    """
    if not memos:
        return ""
    lines = "\n".join(f"- {title}: {text}" for title, text in memos)
    return f"""\
Что этот человек просил учитывать — его собственные слова:
{lines}

Держи это в уме, когда отвечаешь и когда выбираешь инструмент. Вслух не пересказывай
и не напоминай человеку о том, что он сам про себя написал. Это не предписания врача,
а его пожелания: сомневаешься — предложи, а не запрещай.
"""


def system_prompt(user: User, modules: List[str], now: datetime = None,
                  character: str = "", memos: Sequence[Tuple[str, str]] = (),
                  autonomy: int = 1) -> str:
    now = now or local_now()
    # Самостоятельность приезжает параметром, а не берётся у человека: она одна
    # на семью и её задаёт администратор (ADR-0008).
    autonomy = AUTONOMY_LEVELS.get(autonomy or 0, "Спрашивает про важное")
    who = f"{user.display_name}"
    if user.relation:
        who += f" ({user.relation})"

    modules_line = ", ".join(modules) if modules else "нет подключённых модулей"

    # Сначала кто ты и как говоришь, потом чего это не отменяет: манера — часть
    # представления, а не поправка к правилам. Памятки — после правил работы,
    # ближе к фактам: это уже не «как говорить», а «что учитывать».
    blocks = [
        "\n".join(part for part in (WHO, character_block(character)) if part),
        TONE,
        TOOLS_RULES,
        # Правила про еду — только тем, у кого включено питание: незачем занимать
        # контекст того, кто модулем не пользуется. Памятки — тем же правилом:
        # что попало в `memos`, решает вызывающий, а он спрашивает по модулям.
        MEAL_RULES if "nutrition" in modules else "",
        memos_block(memos),
        (
            f"Сейчас: {now:%d.%m.%Y %H:%M}.\n"
            f"Ты разговариваешь с: {who}. Семья: «{user.family.name if user.family else 'Семья'}».\n"
            f"Включённые модули этого человека: {modules_line}.\n"
            f"Настройка самостоятельности: «{autonomy}».\n"
        ),
    ]
    return "\n".join(block for block in blocks if block)


