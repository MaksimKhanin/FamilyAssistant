"""Детекторы отчёта о несделанном — честность ассистента в одном месте.

Самый дорогой вид поломки: снаружи «готово, записала», в базе пусто, человек
ушёл уверенным. Ловится это в два эшелона:

1. **Русские регексы** — по умолчанию и всегда первыми: быстрые, бесплатные,
   проверенные прогонами 74/81/82 (номера прогонов testkit). Они же — их
   главная слабость: морфология зашита, и модель, ответившая на другом языке
   или необычными словами, мимо них проскочит.
2. **LLM-судья** (ручка `HONESTY_JUDGE=1`, по умолчанию выключен) — вторая
   ступень над регексом: сработавший детектор переспрашивает модель, правда ли
   реплика отчитывается о выполненном изменении данных, и глушит ответ только
   при подтверждении. Это снижает цену ложного срабатывания (сейчас — целиком
   выброшенный живой ответ) и даёт языконезависимый путь; судья недоступен —
   решает регекс, как решал всегда.

Сюда вынесено из `app/agent/runtime.py` то, что отвечает на вопрос «отчиталась
ли реплика о сделанном»; что с этим делать (одёрнуть, заменить, пометить
историю) — по-прежнему дело цикла.
"""
import re
from typing import Optional

from app.agent.llm import ROUTINE, LLMClient, LLMUnavailable, client as default_client
from app.core.config import settings
from app.core.logging import get_logger

logger = get_logger("honesty")

#: Как выглядит выдуманный отчёт о вызовах. Модель, которой каждый ход показывали
#: перечень её же инструментов внутри её же реплики, рано или поздно дописывает
#: такой перечень сама — вместо того чтобы позвать инструмент. Снаружи это не
#: отличить от работы: человеку сказано «переименовала и запомнила», а не сделано
#: ни того, ни другого.
#:
#: Первым вариантом идёт ровно та приписка, которой перечень возили раньше: её
#: формат сменился, а строки в базе остались, и читать их как правду тоже нельзя.
#: Служебная запись — в скобках или с начала строки: перечень вызовов посреди
#: фразы моделью не пишется, а «вот что я сделала:» в живой речи встречается.
FABRICATED_TRAIL = re.compile(
    r"\n*(?:\[\s*(?:что\s+я\s+(?:тогда\s+)?сделал[аио]?\b"
    r"|что\s+я\s+вызвал[аи]?\b"
    r"|что\s+вернули\s+инструменты\b)"
    r"|^[ \t]*что\s+вернули\s+инструменты\b)"
    r".*\Z",
    re.IGNORECASE | re.DOTALL | re.MULTILINE,
)

#: Слова, которыми ассистент отчитывается о сделанном. Не «манера речи»: каждое
#: из них — утверждение о состоянии данных, и без вызова инструмента любое из них
#: ложно. «Подготовил» сюда не входит намеренно — это честные слова про действие,
#: которое ждёт «да».
DONE_CLAIM = re.compile(
    r"(?<![а-яё])(?:"
    # «занёс» и «занесла» — разные основы, поэтому обе в списке; окончание
    # необязательно, потому что род и число отчёта не меняют.
    r"записал|дописал|вписал|занёс|занес|занесл|внёс|внес|внесл"
    r"|добавил|завёл|завел|создал"
    r"|переименовал|запомнил|сохранил|удалил|стёр|стер|стёрл|стерл|очистил|почистил"
    r"|поставил|назначил|отметил|пометил|обновил|исправил|поправил|отправил"
    r"|зафиксировал|выполнил|сделал"
    r")(?:а|о|и)?(?![а-яё])",
    re.IGNORECASE,
)

#: «Готово» — только с начала фразы: «блюдо готово» в рецепте ни о чём не
#: отчитывается.
DONE_READY = re.compile(r"^[\s\-—«\"']*готово(?![а-яё])", re.IGNORECASE)

#: Когда те же слова отчётом не являются: отрицание, условие, вопрос, чужое
#: действие. Проверяется по всей фразе — грамматического разбора тут нет, и
#: ошибаться лучше в сторону «не отчёт»: цена ложного срабатывания — выброшенный
#: живой ответ.
NOT_A_CLAIM = re.compile(
    r"(?<![а-яё])(?:не|бы|если|когда|ты|вы|тебе|вам|могу|могла|мог|можешь|можно"
    r"|хочешь|давай|надо|нужно|скажи|попроси|просил|хотел)(?![а-яё])|\?",
    re.IGNORECASE,
)


def own_words(text: str) -> str:
    """Реплика без перечня вызовов: и без выдуманного, и без старого настоящего.

    Перечень — служебная запись; в словах ассистента ему места нет ни на экране,
    ни в истории следующего хода, где он читался бы как правда о сделанном.
    Режем до конца реплики: перечень по своей природе хвост, а хвост, начавшийся
    с рассказа о несделанном, дальше правдой не становится.
    """
    return FABRICATED_TRAIL.sub("", text or "").strip()


def looks_fabricated(text: str) -> bool:
    """Модель отчиталась о вызовах прямо в тексте — значит, не вызвала."""
    return bool(text) and own_words(text) != text.strip()


def claims_done(text: str) -> bool:
    """Реплика отчитывается о выполненном действии?

    Разбор идёт по фразам, а не по всему тексту: «готово» в одной фразе и «не»
    в другой — это по-прежнему отчёт, а вот «я бы записал» отчётом не является.
    Фраза с отрицанием, условием, вопросом или обращением на «ты» отчётом не
    считается: ошибка в эту сторону стоит нам пропущенного обмана, ошибка в
    другую — выброшенного живого ответа.
    """
    for phrase in re.split(r"(?<=[.!?\n])\s*", text or ""):
        if not (DONE_READY.match(phrase) or DONE_CLAIM.search(phrase)):
            continue
        if NOT_A_CLAIM.search(phrase):
            continue
        return True
    return False


# --- вторая ступень: LLM-судья ---------------------------------------------

JUDGE_SYSTEM = """\
Ты проверяешь одну реплику ассистента. Вопрос ровно один: утверждает ли реплика,
что ассистент УЖЕ ВЫПОЛНИЛ действие с данными — записал, удалил, изменил,
сохранил, поставил напоминание?

Отвечай ТОЛЬКО объектом JSON: {"claim": true} или {"claim": false}

- «Готово, записала на доску» → true
- «Могу записать — сказать когда?» → false
- «Подготовила действие, ждёт вашего подтверждения» → false
- «Блюдо готово через 20 минут» → false

Сомневаешься — true: пропущенный обман дороже переспрошенной фразы.
"""


def confirmed_claim(text: str, llm: Optional[LLMClient] = None) -> bool:
    """Вторая ступень над сработавшим регексом.

    Без ручки `HONESTY_JUDGE=1` (умолчание) регекс решает сам — поведение
    прежнее, бесплатное. С ручкой сработавший детектор переспрашивает модель
    и глушит ответ только при подтверждении. Судья недоступен или ответил
    мусором — верим регексу: честность не должна зависеть от связи.
    """
    if not settings.honesty_judge:
        return True
    llm = llm or default_client
    try:
        raw = llm.json_completion(JUDGE_SYSTEM, f"Реплика ассистента:\n{text}", task=ROUTINE)
    except LLMUnavailable:
        return True
    except Exception as error:
        logger.warning(f"Судья честности не ответил ({error!r}) — решает регекс")
        return True
    if not isinstance(raw, dict) or "claim" not in raw:
        return True
    return bool(raw.get("claim"))
