"""Кому какой экран открыт: администратору или участнику.

Ролей две, и они не пересекаются (ADR-0008). Администратор настраивает панель
для всех — учётные записи, модель и деньги, камеры, трейсы. Участник ею
пользуется — разговор, модули, свои знания и свой профиль. Пересечение ровно
одно: свой пароль и своё оформление меняет каждый.

Правило записано **один раз и здесь**, потому что его читают двое:

  * навигация — чтобы не рисовать пункт, на который человека всё равно не пустят;
  * гейт в `app/main.py` — чтобы адрес, набранный руками, тоже не открылся.

Из этого следует важное умолчание: **новый экран считается участниковым**.
Модуль, добавивший себе страницу, получает её для семьи, а не для админа; чтобы
экран стал админским, его адрес нужно назвать здесь явно. Умолчание выбрано так
нарочно: забытый экран лучше спрячет админ-раздел, чем откроет его.
"""
from typing import Optional

AREA_ADMIN = "admin"
AREA_MEMBER = "member"
AREA_ANY = "any"

#: Админ-раздел. Настройки кубиков живут вместе с самими кубиками (камеры — в
#: модуле безопасности), поэтому список адресов, а не один общий префикс.
ADMIN_PREFIXES = (
    "/settings/accounts",        # люди, приглашения, роли, модули каждому
    "/settings/agent",           # самостоятельность и режимы инструментов — на всех
    "/settings/model",           # ядро, зрение, деньги, база знаний семьи
    "/settings/traces",          # трейсы агента
    "/onboarding",               # первая настройка семьи — та же админская работа
    "/security/cameras",         # настройки кубика «Безопасность»
    "/security/control",         # пульт камеры — с того же экрана
    "/security/camera-preview",
)

#: Ни на кого не смотрит: вход, приглашение, статика, ingest с камер, служебное.
#: Гейт их пропускает, не заглядывая в роль, — иначе админ не смог бы выйти.
OPEN_PREFIXES = (
    "/login", "/logout", "/invite", "/static/", "/api/",
    "/sw.js", "/manifest.webmanifest", "/favicon.ico", "/healthz",
)

#: Общее для обеих ролей — и это ровно профиль, поэтому список точечный: сам
#: экран открыт всем, а личные настройки на нём (характер, памятки, инструменты,
#: цели питания) остаются участниковыми, потому что их адресов здесь нет.
SHARED_ROUTES = frozenset({
    ("GET", "/settings/profile"),
    ("POST", "/settings/profile/theme"),
    ("POST", "/settings/profile/password"),
})

#: Куда попадает человек, войдя в панель. У ролей разные «главные»: участнику —
#: обзор дня, администратору — люди, потому что с них начинается вся его работа.
HOME = {AREA_ADMIN: "/settings/accounts", AREA_MEMBER: "/"}

DENIED_FOR_ADMIN = (
    "Это личный экран участника. У администратора нет ни разговора с ассистентом, "
    "ни своих модулей: чтобы пользоваться ассистентом, заведите себе отдельную "
    "учётную запись участника."
)
DENIED_FOR_MEMBER = (
    "Это админский экран: настройки, учётные записи и трейсы ведёт администратор. "
    "Всё, что касается лично вас, — на экране «Профиль и агент»."
)


def area_of(path: str, method: str = "GET") -> str:
    """К какому разделу относится адрес. Умолчание — участниковый."""
    if path.startswith(OPEN_PREFIXES):
        return AREA_ANY
    if (method.upper(), path.rstrip("/") or "/") in SHARED_ROUTES:
        return AREA_ANY
    if path.startswith(ADMIN_PREFIXES):
        return AREA_ADMIN
    return AREA_MEMBER


def area_of_user(user) -> str:
    return AREA_ADMIN if user.is_admin else AREA_MEMBER


def may_open(user, path: str, method: str = "GET") -> bool:
    """Пустить ли `user` на этот адрес. Без человека решает не эта функция, а вход."""
    if user is None:
        return True
    area = area_of(path, method)
    return area == AREA_ANY or area == area_of_user(user)


def home_for(user) -> str:
    return HOME[area_of_user(user)]


def denial_text(user) -> str:
    return DENIED_FOR_ADMIN if user.is_admin else DENIED_FOR_MEMBER


def visible_nav(user, url: str) -> bool:
    """Показывать ли пункт навигации, ведущий на этот адрес."""
    return may_open(user, url)


def redirect_home(user, path: str) -> Optional[str]:
    """Куда отправить человека вместо чужой «главной».

    Отдельный случай ради одного адреса: `/` — это главная участника, но по ней
    же приходят после входа и с иконки на телефоне. Админа там встречала бы
    заглушка «не ваш экран», хотя нужен ему просто другой дом.
    """
    return home_for(user) if path in ("/", "") and not may_open(user, path) else None
